test('ошибки доступа, валидации и сети не меняют данные; запрос можно повторить', async ({ page }) => {
  await page.goto('/transactions')
  const card = page.getByRole('listitem').filter({ hasText: 'Покупки на неделю' })
  await card.getByRole('link', { name: 'Редактировать' }).click()
  await page.getByLabel('Сумма, ₽').fill('999')
  for (const [status, detail, expected] of [
    [403, 'Нет доступа к этой операции.', 'Нет доступа к этой операции.'],
    [422, [{ loc: ['body', 'amount_kopecks'], msg: 'Invalid' }], 'Проверьте правильность введённых данных.'],
  ] as const) {
    await page.route('**/api/transactions/*', (route) => route.fulfill({ status, json: { detail } }))
    await page.getByRole('button', { name: 'Сохранить изменения' }).click()
    await expect(page.getByText(expected)).toBeVisible()
    await expect(page.getByLabel('Сумма, ₽')).toHaveValue('999')
    await page.unroute('**/api/transactions/*')
  }
  await page.getByRole('link', { name: 'Отмена', exact: true }).click()
  await expect(card).toContainText(/3\s?250,50/)
  await card.getByRole('button', { name: 'Удалить операцию' }).click()
  await page.route('**/api/transactions/*', (route) => route.abort('failed'))
  await page.getByRole('dialog').getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect(page.getByText('Не удалось связаться с сервером.', { exact: false })).toBeVisible()
  await page.unroute('**/api/transactions/*')
  await page.getByRole('dialog').getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect(card).toHaveCount(0)
  await page.reload()
  await expect(card).toHaveCount(0)
})

test('списки API загружаются полностью при количестве операций больше 100', async ({ page, context, account }) => {
  const categories: { id: string; name: string }[] = await (await authorized(context.request, account, 'GET', '/categories')).json()
  const category = categories.find((item) => item.name === 'Продукты')!
  for (let index = 0; index < 101; index++) {
    await authorized(context.request, account, 'POST', '/transactions', {
      category_id: category.id, amount_kopecks: 1, date: '2020-01-01', comment: `Пагинация ${index}`,
    })
  }
  await page.goto('/transactions')
  await expect(page.getByRole('status')).toHaveText('Найдено: 107')
  await page.getByLabel('Дата', { exact: true }).fill('01.01.2020')
  await expect(page.getByRole('status')).toHaveText('Найдено: 101')
  await page.getByRole('link', { name: 'Обзор', exact: true }).click()
  await chooseMonth(page, '2020-01')
  await expect(page.getByTestId('expense-total')).toHaveText('1,01 ₽')
})


test('реальная пустая выборка категорий и создание категории через интерфейс', async ({ page, context }) => {
  const emptyAccount = await createAccount(context.request)
  const categories: { id: string }[] = await (await authorized(context.request, emptyAccount, 'GET', '/categories')).json()
  for (const category of categories) await authorized(context.request, emptyAccount, 'DELETE', `/categories/${category.id}`)
  await page.goto('/categories')
  await expect(page.getByText('Категорий пока нет')).toBeVisible()
  await capture(page, 'categories-empty')
  await page.getByRole('button', { name: 'Добавить категорию', exact: true }).click()
  await page.getByLabel('Название категории').fill('Первая категория')
  await page.getByRole('dialog').getByRole('button', { name: 'Добавить категорию', exact: true }).click()
  await expect(page.getByRole('listitem').filter({ hasText: 'Первая категория' })).toBeVisible()
  await expect(page.getByText('Категорий пока нет')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('listitem').filter({ hasText: 'Первая категория' })).toBeVisible()
  await page.getByRole('link', { name: 'Операции', exact: true }).click()
  await page.getByRole('link', { name: 'Добавить операцию', exact: true }).click()
  await page.getByRole('combobox', { name: 'Категория', exact: true }).click()
  await expect(page.getByRole('option', { name: 'Первая категория', exact: true })).toBeVisible()
})
