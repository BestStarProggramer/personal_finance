test('удаление и повторное создание лимита сохраняют операции и другие месяцы', async ({ page, context, account }) => {
  await page.goto('/budgets')
  const food = page.getByRole('region', { name: 'Продукты', exact: true })
  await food.getByRole('button', { name: 'Удалить лимит' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect(food).toContainText('Лимит не задан')
  await expect(food).toContainText(/Потрачено: 3\s?250,50/)
  await expect(page.getByRole('region', { name: 'Жильё', exact: true })).toContainText(/Лимит: 25\s?000,00/)
  await page.reload()
  await expect(food).toContainText('Лимит не задан')
  await chooseMonth(page, '2020-01')
  await page.getByLabel('Лимит, ₽').fill('1000')
  await page.getByRole('button', { name: 'Сохранить лимит' }).click()
  await expect(food).toContainText(/Лимит: 1\s?000,00/)
  await chooseMonth(page, new Date().toLocaleDateString('sv-SE', { timeZone: 'Europe/Moscow' }).slice(0, 7))
  await expect(food).toContainText('Лимит не задан')
  await page.getByLabel('Лимит, ₽').fill('4000')
  await page.getByRole('button', { name: 'Сохранить лимит' }).click()
  await expect(food).toContainText(/Лимит: 4\s?000,00/)
  await page.getByLabel('Лимит, ₽').fill('4500')
  await page.getByRole('button', { name: 'Сохранить лимит' }).click()
  await expect(food).toContainText(/Лимит: 4\s?500,00/)
  await page.reload()
  await expect(food).toContainText(/Лимит: 4\s?500,00/)
  await chooseMonth(page, '2020-01')
  await expect(food).toContainText(/Лимит: 1\s?000,00/)
  const transactions = await (await authorized(context.request, account, 'GET', '/transactions')).json()
  expect(transactions).toHaveLength(6)
})

